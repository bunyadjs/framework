/**
 * Output sinks for `SitemapWriter`. A sink is a flat directory of named files.
 * `fileSink` uses `node:fs` streams (Bun + Node); `memorySink` is for tests and
 * small in-process use. Disk (`@bunyad/filesystem`) sink arrives in Phase 2.
 */
import { createReadStream, createWriteStream } from "node:fs";
import { mkdir, readdir, rename, rm } from "node:fs/promises";
import { join, resolve, sep } from "node:path";

export interface SinkWritable {
  write(chunk: Uint8Array): Promise<void>;
  close(): Promise<void>;
  abort(): Promise<void>;
}

export interface SitemapSink {
  open(name: string): Promise<SinkWritable>;
  read(name: string): AsyncIterable<Uint8Array>;
  move(from: string, to: string): Promise<void>;
  delete(name: string): Promise<void>;
  list(): Promise<string[]>;
}

const SAFE_NAME = /^[A-Za-z0-9._-]+$/;

/** Sink names are generated by the writer, but guard anyway (no traversal). */
export function assertSafeName(name: string): string {
  if (!SAFE_NAME.test(name) || name === "." || name === "..") {
    throw new Error(`Unsafe sitemap file name [${name}].`);
  }
  return name;
}

/** Files under `directory` (created on first write). */
export function fileSink(directory: string): SitemapSink {
  const root = resolve(directory);
  const full = (name: string) => {
    const path = join(root, assertSafeName(name));
    if (!path.startsWith(root + sep))
      throw new Error(`Unsafe sitemap file name [${name}].`);
    return path;
  };
  return {
    async open(name) {
      await mkdir(root, { recursive: true });
      const path = full(name);
      const out = createWriteStream(path);
      let failure: unknown = null;
      out.on("error", (error) => {
        failure ??= error;
      });
      await new Promise<void>((ok, fail) => {
        out.once("open", () => ok());
        out.once("error", fail);
      });
      return {
        write(chunk) {
          if (failure) return Promise.reject(failure);
          if (out.write(chunk)) return Promise.resolve();
          return new Promise<void>((ok, fail) => {
            const onDrain = () => {
              out.off("error", onError);
              ok();
            };
            const onError = (error: unknown) => {
              out.off("drain", onDrain);
              fail(error);
            };
            out.once("drain", onDrain);
            out.once("error", onError);
          });
        },
        close() {
          return new Promise<void>((ok, fail) => {
            if (failure) {
              fail(failure);
              return;
            }
            out.end((error?: Error | null) => (error ? fail(error) : ok()));
          });
        },
        async abort() {
          out.destroy();
          await rm(path, { force: true });
        },
      };
    },
    async *read(name) {
      for await (const chunk of createReadStream(full(name), {
        highWaterMark: 1 << 16,
      })) {
        yield chunk as Uint8Array;
      }
    },
    async move(from, to) {
      await rename(full(from), full(to));
    },
    async delete(name) {
      await rm(full(name), { force: true });
    },
    async list() {
      try {
        return await readdir(root);
      } catch {
        return [];
      }
    },
  };
}

export type MemorySink = SitemapSink & {
  readonly files: Map<string, Uint8Array>;
  text(name: string): string;
};

/** In-memory sink (tests, small sitemaps). */
export function memorySink(): MemorySink {
  const files = new Map<string, Uint8Array>();
  const decoder = new TextDecoder();
  return {
    files,
    text(name) {
      const data = files.get(name);
      if (!data) throw new Error(`No sitemap file [${name}].`);
      return decoder.decode(data);
    },
    async open(name) {
      assertSafeName(name);
      const chunks: Uint8Array[] = [];
      let size = 0;
      return {
        async write(chunk) {
          chunks.push(chunk.slice());
          size += chunk.byteLength;
        },
        async close() {
          const data = new Uint8Array(size);
          let offset = 0;
          for (const c of chunks) {
            data.set(c, offset);
            offset += c.byteLength;
          }
          files.set(name, data);
        },
        async abort() {
          chunks.length = 0;
        },
      };
    },
    async *read(name) {
      const data = files.get(name);
      if (!data) throw new Error(`No sitemap file [${name}].`);
      yield data;
    },
    async move(from, to) {
      const data = files.get(from);
      if (!data) throw new Error(`No sitemap file [${from}].`);
      files.delete(from);
      files.set(assertSafeName(to), data);
    },
    async delete(name) {
      files.delete(name);
    },
    async list() {
      return [...files.keys()];
    },
  };
}
